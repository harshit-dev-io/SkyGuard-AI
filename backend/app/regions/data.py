# Helper to normalize region ID slug
def normalize_region_id(name_or_id: str) -> str:
    s = name_or_id.lower().replace("&", "and").replace("-", "_").replace(" ", "_")
    while "__" in s:
        s = s.replace("__", "_")
    return s.strip("_")

# Build Complete District Summaries for Any State
def get_districts_for_region(region_id: str) -> List[Dict[str, Any]]:
    clean_id = normalize_region_id(region_id)
    region = next((r for r in INDIAN_REGIONS if r["id"] == clean_id or normalize_region_id(r["name"]) == clean_id), None)
    if not region:
        # Fallback to search by state code or prefix
        region = next((r for r in INDIAN_REGIONS if r["code"].lower() == clean_id or clean_id.startswith(r["id"])), None)
    
    if not region:
        return []

    r_id = region["id"]
    r_name = region["name"]
    entries = STATE_DISTRICT_REGISTRY.get(r_id, [])

    results = []
    for idx, d in enumerate(entries, 1):
        d_name = d["name"]
        d_id = normalize_region_id(d_name)
        lat, lng = d["center"]
        bounds = [
            [round(lat - 0.22, 4), round(lng - 0.22, 4)],
            [round(lat + 0.22, 4), round(lng + 0.22, 4)]
        ]
        results.append({
            "id": d_id,
            "name": d_name,
            "region_id": r_id,
            "region_name": r_name,
            "center": [lat, lng],
            "bounds": bounds,
            "station_count": d.get("stations", 12),
            "healthy": d.get("h", 10),
            "anomalies": d.get("a", 1),
            "faults": d.get("f", 1),
            "drift": 0,
            "unknown": 0,
            "elevation": d.get("elev", 250),
        })
    return results

